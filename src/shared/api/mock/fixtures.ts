export function buildAuthors(): Author[] {
  return authors.map(({ id, full_name }) => {
    const authorBooks = books
      .filter((b) => b.authors.some((a) => a.id === id))
      .map(({ id: bookId, title, year }) => ({ id: bookId, title, year }))
    return { id, full_name, books: authorBooks }
  })
}